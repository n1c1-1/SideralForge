"""post_wires round 2: after "Pause vérif" on a block, is its menu all greyed? (Output block vs a middle block); the
Output block's menu "Supprimer"."""
from explore_post_common import CHAINS, P, Explorer, build_chain, session_project, start

start(300)
ex = Explorer("post_wires")
pp = P(ex)
for target in ("fond", "post"):
    session_project(ex)
    build_chain(ex, CHAINS["color"])
    ex.right_click_block(pp.block("fond"), "Vers Post")
    ex.settle(6)
    get = (lambda: pp.blocks_of("post")[0]) if target == "post" else (lambda: pp.block("fond", pid=ex.s.paths[0].pid))
    m0 = ex.right_click_block(get())
    ex.right_click_block(get(), "Pause vérif")
    ex.settle(6)
    m = ex.right_click_block(get())
    print(target, "toast", repr(pp.toast()))
    print("  before", [(d.get("text"), d.get("enabled")) for d in m0 if d.get("text") != "---"])
    print("  after ", [(d.get("text"), d.get("enabled"), d.get("tip")) for d in m if d.get("text") != "---"])
    print("  other block menu (couleur)", [(d.get("text"), d.get("enabled")) for d in ex.right_click_block(pp.block("couleur"))
                                           if d.get("text") != "---"])
    ex.shot(f"pause_{target}")
    pp.undo()
    m = ex.right_click_block(get())
    print("  after Ctrl+Z", [(d.get("text"), d.get("enabled")) for d in m if d.get("text") != "---"][:4], repr(pp.toast()))
session_project(ex)
build_chain(ex, CHAINS["color"])
ex.right_click_block(pp.block("fond"), "Vers Post")
ex.settle(6)
ex.right_click_block(pp.blocks_of("post")[0], "Supprimer")
ex.settle(6)
print("menu Supprimer on output:", repr(pp.toast()), [q.name for q in ex.s.paths])
ex.close()
