"""post_wires round 2: the message after an Image placed in a blank project; the Fusion channels."""
from explore_post_common import P, Explorer, start

start(300)
ex = Explorer("post_wires")
pp = P(ex)
ex.new_project("Vide")
ex.w.activateWindow()
print("after new project: toast", repr(pp.toast()), [b.node.key for b in ex.blocks()])
ex.double_click_card("image")
ex.settle(8)
print("after image dbl: toast", repr(pp.toast()), [b.node.key for b in ex.blocks()], ex.file_asks)
ex.shot("probe_image_toast")
ex.double_click_card("image")
ex.settle(8)
print("after 2nd image dbl: toast", repr(pp.toast()), [(b.node.key, b.title) for b in ex.blocks()])
root = ex.project("mono")
ex.open(root)
ex.w.activateWindow()
print("mono before:", [(q.name, [n['block'] for n in (ex.s.p.workflow(q.pid).blocks or [])]) for q in ex.s.paths])
print("blocks before:", pp.blocks_desc())
ex.double_click_card("fusion")
ex.settle(8)
print("mono after:", [(q.name, [n['block'] for n in (ex.s.p.workflow(q.pid).blocks or [])]) for q in ex.s.paths])
print("blocks after:", pp.blocks_desc(), "toast", pp.toast())
ex.shot("probe_fusion")
ex.close()
