def reduce_map(a: np.ndarray, f: int) -> np.ndarray:
    """(C, H, W) reduced by a whole factor ``f`` (the rejection maps' grid): the mean of each f x f block (of its
    pixels inside the image), float32."""
    a = np.asarray(a, np.float32)
    if f <= 1:
        return a.copy()
    C, H, W = a.shape
    Hr, Wr = -(-H // f), -(-W // f)
    out = np.empty((C, Hr, Wr), np.float32)
    cnt = np.zeros((Hr, Wr), np.float32)
    ones = np.ones((H, W), np.float32)
    pad = ((0, Hr * f - H), (0, Wr * f - W))
    cnt[:] = np.pad(ones, pad).reshape(Hr, f, Wr, f).sum((1, 3))
    for c in range(C):
        out[c] = np.pad(a[c], pad).reshape(Hr, f, Wr, f).sum((1, 3), dtype=np.float64) / cnt
    return out


def coverage_record(wmap: torch.Tensor, f: int, coef_used, W: int, H: int, cfa: str, S: float, PIX: float,
                    w_used, suggestion) -> dict:
    """The coverage of a stack for Inspect and the bench (core/coverage.py): its weight map ``wmap`` (3, Ho, Wo) per
    colour reduced by ``f`` and its variation (std / median, DrizzlePac's statistic, without 10 % margins), the fast
    estimate at the scale and drop used, and the rule's ``suggestion`` on the frames kept (scale, drop, method
    advice). ``arrays`` go to coverage.npz, the rest to diagnostics.json."""
    from ..core import coverage as cv
    w = wmap.cpu().numpy()
    measured = cv.map_variation(w)
    red = reduce_map(w, f)
    del w
    est = cv.coverage(coef_used, W, H, cfa, S, PIX, weights=w_used)
    rec = {"factor": int(f), "scale": float(S), "pixfrac": float(PIX), "limit": cv.LIMIT,
           "measured_cv": [measured[c] for c in cv.CHANNELS],
           "estimate_cv": [est.cv.get(c) for c in cv.CHANNELS], "estimate_cv_max": [est.cv_max.get(c) for c in cv.CHANNELS]}
    rec["measured_cv"] = [_num(v) for v in rec["measured_cv"]]
    rec["estimate_cv"] = [_num(v) for v in rec["estimate_cv"]]
    rec["estimate_cv_max"] = [_num(v) for v in rec["estimate_cv_max"]]
    s = suggestion
    rec["rule"] = {"fwhm": _num(s.fwhm), "scale": _auto_dict(s.scale), "pixfrac": _auto_dict(s.pixfrac),
                   "method": _auto_dict(s.method)}
    rec["arrays"] = {"measured": red, "variation": np.array([np.nan if v is None else v for v in rec["measured_cv"]]),
                     "estimate_map": np.stack([est.cv_map.get(c, np.full(est.cv_map["R"].shape, np.nan))
                                               for c in cv.CHANNELS]).astype(np.float32),
                     "factor": int(f)}
    return rec


def fixed_pattern(mm, used, coef, dev, H, W, nframes, progress=lambda f: None, period: int = 2):
    """Sensor fixed pattern, per position of the colour pattern (``period``: 2 for Bayer, 6 for X-Trans), in sensor
    coordinates.

    The sky drifts across the sensor while the pattern stays: stars and sky structures smaller than the drift fall
    on a pixel in a few frames only. Pass 1: median over ``nframes`` frames spread over the session (frames minus
    their smooth sky). Pass 2: mean over all used frames of the values within 3 sigma of that median (stars, cosmic
    rays and trails rejected), streamed, so that the estimate is precise enough not to add its own noise. Scales
    above a quarter of the drift are not kept (larger sky structures are not averaged out).
    Returns (pattern (H, W) on ``dev`` or None, info).
    """
    sel = used[np.unique(np.linspace(0, len(used) - 1, min(nframes, len(used))).round().astype(int))]
    tx, ty = coef[used, 0, 0], coef[used, 1, 0]                            # field-centre position (pixels)
    drift = float(np.hypot(np.ptp(tx), np.ptp(ty)))
    if drift < 12 or len(used) < 8:
        return None, {"applied": False, "drift_px": round(drift, 1), "frames": int(len(used)),
                      "msg": f"fixed pattern not measured: the sky drifted by {drift:.0f} px only over the session "
                             f"(too little to tell the pattern from the sky)"}
    P = int(period)
    NP = P * P
    Hh, Wh = H // P, W // P

    def residuals(i):
        """(NP, Hh, Wh) frame minus its smooth sky per pattern position (NaN where saturated / bad), noise per
        plane."""
        fr = torch.from_numpy(np.asarray(mm[i], np.float32)).to(dev)
        out, sg = [], []
        for k in range(NP):
            ky, kx = divmod(k, P)
            pl = fr[ky::P, kx::P][:Hh, :Wh]
            pl = torch.where(pl > VALID_MAX, torch.nan, pl)
            sky = _plane_sky(pl)
            r = pl - sky
            sub = r[::7, ::7]
            sg.append(1.4826 * torch.nanmedian((sub - torch.nanmedian(sub)).abs()))
            out.append(r)
        return torch.stack(out), torch.stack(sg)

    planes = np.zeros((len(sel), NP, Hh, Wh), np.float16)
    for j, i in enumerate(sel):
        planes[j] = residuals(i)[0].cpu().numpy().astype(np.float16)
        progress(0.3 * (j + 1) / len(sel))
    med = torch.zeros(NP, Hh, Wh, device=dev)
    for y0 in range(0, Hh, 128):
        blk = torch.from_numpy(planes[:, :, y0:y0 + 128].astype(np.float32)).to(dev)
        med[:, y0:y0 + 128] = torch.nanmedian(blk, dim=0).values.nan_to_num(0.0)
    del planes
    acc = torch.zeros(NP, Hh, Wh, device=dev)
    cnt = torch.zeros(NP, Hh, Wh, device=dev)
    for j, i in enumerate(used):
        r, sg = residuals(i)
        keep = ((r - med).abs() < 3 * sg[:, None, None]) & torch.isfinite(r)
        acc += torch.where(keep, r, torch.zeros_like(r))
        cnt += keep.float()
        progress(0.3 + 0.7 * (j + 1) / len(used))
    pat = torch.where(cnt > 0, acc / cnt.clamp(min=1), med)
    sig = float(np.clip(drift / P / 4, 2.0, 16.0))                   # a quarter of the drift, in plane pixels
    out = torch.zeros(H, W, device=dev)
    amp = []
    for k in range(NP):
        ky, kx = divmod(k, P)
        hp = pat[k] - _gauss(pat[k], sig)
        sub = hp[::3, ::3]
        amp.append(float(1.4826 * torch.median((sub - torch.median(sub)).abs())))
        out[ky::P, kx::P][:Hh, :Wh] = hp
    info = {"applied": True, "drift_px": round(drift, 1), "frames": int(len(used)), "scale_px": round(P * sig, 1),
            "amplitude_adu": [round(a, 3) for a in amp],
            "msg": f"fixed pattern measured on {len(used)} frames (sky drift {drift:.0f} px): amplitude "
                   f"{np.mean(amp):.2f} ADU per pixel, removed from every frame"}
    return out, info


def _plane_sky(pl: torch.Tensor, b: int = 32) -> torch.Tensor:
    """Smooth sky of a Bayer plane: medians of b x b blocks, bilinearly interpolated."""
    Hh, Wh = pl.shape
    nby, nbx = Hh // b, Wh // b
    blk = pl[: nby * b, : nbx * b].reshape(nby, b, nbx, b).permute(0, 2, 1, 3).reshape(nby, nbx, b * b)
    m = torch.nanmedian(blk, dim=-1).values
    m = torch.where(torch.isfinite(m), m, torch.nanmedian(m))
    up = F.interpolate(m[None, None], size=(nby * b, nbx * b), mode="bilinear", align_corners=False)
    return F.pad(up, (0, Wh - nbx * b, 0, Hh - nby * b), mode="replicate")[0, 0]


def _gauss(x: torch.Tensor, sigma: float) -> torch.Tensor:
    r = int(4 * sigma + 0.5)
    t = torch.arange(-r, r + 1, device=x.device, dtype=torch.float32)
    k = torch.exp(-0.5 * (t / sigma) ** 2)
    k = k / k.sum()
    y = F.pad(x[None, None], (r, r, r, r), mode="reflect")
    y = F.conv2d(y, k.view(1, 1, 1, -1))
    return F.conv2d(y, k.view(1, 1, -1, 1))[0, 0]
