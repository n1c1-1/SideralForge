"""Stacking: weighted Bayer drizzle on the GPU with predictive outlier rejection and two independent half-stacks,
or the Classic method (debayering and interpolated registration, ``stack_classic``).

- ``method = drizzle | classic``. The engine advises one (the automatic value "method", an advice only:
  core/coverage.advise_method, on the frames the selection keeps); it never changes the method by itself.
- The drizzle scale and drop size are suggested from register's Moffat FWHM and the coverage of the red and blue
  samples of the frames kept (core/coverage.py, DrizzlePac's 20 % rule).
- ``selection``: ``min_weight`` (default) keeps every aligned frame unless its weight is under 5 % of the best one,
  and lets the weights handle the bad ones; ``sota`` first applies k x sigma filters at 2.5 on FWHM, roundness and
  transparency (``selection_transparency = off`` drops the last); ``thresholds`` leaves out the frames under a
  minimum transparency or over a maximum star size, set by the user (on the Selection chart). Frames excluded by hand
  are left out in every mode. The weights are (transparency / noise)^2 x sharpness.
- ``drizzle_rejection = own`` (default) or ``integration``: how the Bayer drizzle finds its outliers.
  ``integration`` is the method for a CFA drizzle of [P18][P19]: the rejection of an image integration (the Classic
  method's, chosen by the number of frames) runs on the debayered, registered frames, and what it rejects in a frame
  is left out of that frame's drops on the same output pixels (``integration_rejection``, ``deposit``'s ``rej``).
  The Classic method's settings (debayering, interpolation, clamping, rejection, white balance) then apply to it.
- The colour channels are aligned for the whole night (``ChannelOffsets``).

Outputs besides the stack: coverage.npz (the weight map per colour, reduced, its variation and the coverage rule's
estimate), frames.json (every frame, its weight and why it was left out), diagnostics.json (selection, coverage,
rejection, normalisation of each frame, noise).

Sources of the integration's rejection: [P18] PCL DrizzleData, "pixel
rejection data generated by a regular image integration task", a rejection map per channel on the registered image,
bits for low and high rejection, https://www.pixinsight.com/developer/pcl/doc/html/classpcl_1_1DrizzleData.html ;
[P19] DrizzleIntegration (``enableRejection``, on by default), PCL src/modules/processes/ImageIntegration/
DrizzleIntegrationInstance.cpp (2016: https://github.com/aleixpuig/PCL ; 2021 with CFA drizzle, read from a copy of
PCL at https://github.com/fmeschia/pixinsight-class-library): for each output pixel, q = the reference pixel holding
its top-left corner (+ DRIZZLE_BOUNDS_TOLERANCE); a source pixel of CFA channel c adds nothing to it when
``RejectionMap()(q, c) != 0``.

"""
