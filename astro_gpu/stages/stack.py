def white_balance_of(ctx: Context, p: StackParams, meta: list[dict]) -> np.ndarray | None:
    """The camera's daylight white balance (io.frames.daylight_balance) of the first light frame, when the setting
    asks for it and the frames are raw; logged."""
    if not p.white_balance or not meta:
        return None
    from ..io.frames import daylight_balance
    try:
        wb = daylight_balance(meta[0]["path"])
    except Exception as e:  # noqa: BLE001 - a frame unreadable here was read by the calibration: no balance then
        ctx.log(f"camera white balance not read ({e}): the stack keeps the camera's colours", "warning")
        return None
    if wb is None:
        ctx.log("the frames hold no camera white balance: the stack keeps the colours of the frames")
        return None
    ctx.log(f"camera white balance: red x {wb[0]:.3f}, blue x {wb[2]:.3f} (green 1)")
    ctx.metric("camera_white_balance", [round(float(v), 4) for v in wb])
    return wb


def balanced(a: np.ndarray, wb: np.ndarray | None) -> np.ndarray:
    """An image of the stack (3, H, W) through the camera's white balance (or as it is)."""
    return a if wb is None else (a * wb.astype(a.dtype)[:, None, None])


def stack_classic(ctx: Context, p: StackParams, *, wb=None, load, coef, used, weight, norm, transp, meta, sel, ch_of_k,
                  H: int, W: int, satval, dev, t0: float, colour: bool = False, zone=None) -> None:
    """The hook of the Classic method (``method = classic``: RCD debayering, Lanczos-4
    registration with Siril's clamping, WBPP's rejection by frame count; core/stack_classic.py and the modules it
    uses). ``Stack.run`` calls it once the part both methods share is done: the frames ``used`` with their
    ``weight``, the normalisation (``norm`` {frame: (Q, sky)} of frame_norm and ``transp``), the selection ``sel``
    (``Selection``), ``load(i)`` the calibrated CFA frame. It writes what the drizzle writes (drz_full / drz_A /
    drz_B / drz_weight.npy, saturation.npy, drz_meta.json, rejection.npz, diagnostics.json), at the sensor's
    resolution, so that the stages after it read them unchanged. Without the Classic modules it says so
    (StageError)."""
    if classic_missing():
        raise StageError(CLASSIC_NOT_YET)
    from ..core import stack_classic as sc
    nm = sc.Norm.from_drizzle(norm, transp)
    res = sc.stack_classic(load, coef, bad=None, norm=nm, weights=weight, params=classic_params(p),
                           device=dev, used=used, ch_of_k=ch_of_k, H=H, W=W, sat_level=satval,
                           progress=lambda f, msg: ctx.progress(0.05 + 0.95 * f, msg),
                           raw_template=raw_template(meta, used, ch_of_k), colour=colour, **within_memory(ctx))
    mono = cfa_mod.is_mono(meta[0].get("cfa", "")) if meta else False
    for name, a in res.arrays().items():
        if name in ("drz_full.npy", "drz_A.npy", "drz_B.npy"):
            a = balanced(a, wb)
        if mono and name in ("drz_full.npy", "drz_A.npy", "drz_B.npy", "drz_weight.npy"):
            a = cfa_mod.mono_rgb(a)
        if zone is not None:                        # the Classic stack is made whole, then cut (issue #79)
            a = a[..., zone[1]:zone[3], zone[0]:zone[2]]
        ctx.save(name, a)
    res.save_rejection(ctx.out(REJECTION))
    ctx.metric("grid", [W, H])
    ctx.metric("rejected_pct", round(float(res.rejected_pct), 3))
    ctx.metric("near_saturation_pct", round(100 * float((res.saturation[0] > 0).mean()), 4))
    switches = {**p.switches(), **{k: getattr(p, k) for k in CLASSIC_CHOICES}}
    cut = {"width": zone[2] - zone[0], "height": zone[3] - zone[1], "zone": zone} if zone else {}
    ctx.save_json("drz_meta.json", {**res.meta(), **cut, "switches": switches})
    frames_d = []
    for f in res.frames:                    # the drizzle's record of each frame (its normalisation), and Classic's
        i = int(f["index"])
        q, sky = norm[i]
        nd = {"scale": [float(1.0 / transp[i])] * 3, "offset": [float(v) for v in q[:, 0]],
              "gradient": q.tolist(), "sky": sky.tolist()}
        frames_d.append({"index": i, "path": meta[i]["path"], "weight": float(weight[i]),
                         "transparency": float(transp[i]), **nd, **f})
    diag = {**res.diagnostics(), "frames": frames_d, "kappa": p.kappa, "switches": switches}
    diag["rejection"].update(method="classic", classic=res.choice.method,
                             reason_template={"template": res.choice.template, "args": res.choice.args})
    diag["selection"] = sel.as_dict()
    ctx.save_json(DIAG, diag)
    ctx.log(f"Classic stack {W}x{H} from {len(used)} frames in {(time.time() - t0) / 60:.1f} min: "
            f"{res.choice.reason}; {res.rejected_pct:.2f} % pixels rejected")
    ctx.preview("stack", asinh_preview(balanced(res.full, wb)))


